#!/usr/bin/env python3
"""Static checks for the portfolio. Standard library only.

Run from the site root:  python3 tools/check.py
Exits non-zero if any check fails.
"""
import re
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
PAGES = ["index.html", "404.html"]
REQUIRED_FILES = ["index.html", "404.html", "styles.css", "script.js", "favicon.svg",
                  "robots.txt", "sitemap.xml", ".nojekyll", "assets/og.png",
                  "THIRD_PARTY_NOTICES.md", "LICENSING.md"]
# Things that must never be published.
LEAK_PATTERNS = [
    (r"\(?\b\d{3}\)?[-.\s]\d{3}[-.\s]\d{4}\b", "phone-like number"),
    (r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}", "email address"),  # PUBLIC_EMAIL is exempt
    (r"(?i)evidence library|applicant|job search|cover letter|work authori[sz]ation|visa|sponsorship", "private job-search wording"),
    (r"(?i)\b(api[_-]?key|secret|token|password)\b", "credential wording"),
    (r"(?i)google-analytics|gtag\(|googletagmanager|plausible|document\.cookie", "analytics or cookies"),
    (r"(?i)fonts\.googleapis|fonts\.gstatic", "remote font"),
    (r"(?i)\b(claude|chatgpt|openai|anthropic|generated by|written by ai)\b", "assistant watermark"),
]
PUBLIC_EMAIL = "sashankkuraganti99@gmail.com"  # authorized by the site owner; no other address may appear
SITE_TEXT_FILES = ["index.html", "404.html", "styles.css", "script.js", "robots.txt", "sitemap.xml"]

failures = []
def fail(msg):
    failures.append(msg)


class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids, self.refs, self.imgs, self.metas, self.links = [], [], [], {}, []
        self.anchors, self.headings, self.title, self._in_title = [], [], "", False
        self.lang = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "html":
            self.lang = a.get("lang")
        if "id" in a:
            self.ids.append(a["id"])
        if tag in ("a", "link") and "href" in a:
            self.refs.append((tag, a["href"]))
        if tag in ("img", "script") and "src" in a:
            self.refs.append((tag, a["src"]))
        if tag == "img":
            self.imgs.append(a)
        if tag == "a":
            self.anchors.append(a)
        if tag == "meta":
            key = a.get("name") or a.get("property")
            if key:
                self.metas.setdefault(key, a.get("content", ""))
        if tag == "link":
            self.links.append(a)
        if re.fullmatch(r"h[1-6]", tag):
            self.headings.append(int(tag[1]))
        if tag == "title":
            self._in_title = True

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def local_path(page, ref):
    path = ref.split("#")[0].split("?")[0]
    if not path:
        return None
    if path.startswith("/"):
        target = ROOT / path.lstrip("/")
    else:
        target = (ROOT / page).parent / path
    if path.endswith("/"):
        target = target / "index.html"
    return target


def check_page(name):
    p = Page()
    p.feed((ROOT / name).read_text(encoding="utf-8"))
    if not p.lang:
        fail(f"{name}: <html> has no lang")
    if not p.title.strip():
        fail(f"{name}: empty <title>")
    dupes = {i for i in p.ids if p.ids.count(i) > 1}
    if dupes:
        fail(f"{name}: duplicate ids {sorted(dupes)}")
    if p.headings.count(1) != 1:
        fail(f"{name}: expected exactly one h1, found {p.headings.count(1)}")
    for prev, cur in zip(p.headings, p.headings[1:]):
        if cur > prev + 1:
            fail(f"{name}: heading level jumps from h{prev} to h{cur}")
    for tag, ref in p.refs:
        u = urlparse(ref)
        if u.scheme == "mailto":
            if ref != "mailto:" + PUBLIC_EMAIL:
                fail(f"{name}: unexpected mailto {ref}")
            continue
        if u.scheme in ("http", "https"):
            if u.scheme != "https":
                fail(f"{name}: insecure URL {ref}")
            continue
        if ref.startswith("#"):
            if ref[1:] and ref[1:] not in p.ids:
                fail(f"{name}: fragment {ref} has no matching id")
            continue
        target = local_path(name, ref)
        if target and not target.exists():
            fail(f"{name}: missing local target {ref}")
    for img in p.imgs:
        if "alt" not in img:
            fail(f"{name}: img {img.get('src')} has no alt")
        if not (img.get("width") and img.get("height")):
            fail(f"{name}: img {img.get('src')} has no width/height")
        src = img.get("src", "")
        if src.startswith("http"):
            fail(f"{name}: remote image {src}")
    for a in p.anchors:
        if a.get("target"):
            fail(f"{name}: link {a.get('href')} forces a target")
    return p


def main():
    for f in REQUIRED_FILES:
        if not (ROOT / f).exists():
            fail(f"missing required file {f}")
    pages = {n: check_page(n) for n in PAGES}

    idx = pages["index.html"]
    canonical = [l.get("href") for l in idx.links if l.get("rel") == "canonical"]
    if canonical != ["https://skuraganti.github.io/"]:
        fail(f"index.html: canonical is {canonical}")
    for key in ("description", "og:title", "og:description", "og:image", "og:url", "twitter:card"):
        if not idx.metas.get(key):
            fail(f"index.html: missing meta {key}")
    og = idx.metas.get("og:image", "")
    if og.startswith("https://skuraganti.github.io/") and not (ROOT / og.split("github.io/", 1)[1]).exists():
        fail(f"index.html: og:image file missing locally ({og})")

    html = (ROOT / "index.html").read_text(encoding="utf-8")
    # Independent projects must not carry dates or years.
    work = html.split('id="work"', 1)[1].split('id="skills"', 1)[0]
    years = re.findall(r"\b(?:19|20)\d{2}\b", work)
    if years:
        fail(f"index.html: year-like values inside the projects section: {years}")
    projects = re.findall(r'class="project[^"]*" data-cat="(data|ai)"', work)
    if len(projects) != 7:
        fail(f"index.html: expected 7 projects, found {len(projects)}")

    for f in SITE_TEXT_FILES:
        text = (ROOT / f).read_text(encoding="utf-8")
        for pat, label in LEAK_PATTERNS:
            for m in re.finditer(pat, text):
                if label == "email address" and m.group(0) == PUBLIC_EMAIL:
                    continue
                fail(f"{f}: possible {label}: {m.group(0)!r}")

    for path in ROOT.rglob("*"):
        if path.is_symlink():
            fail(f"symlink not allowed: {path.relative_to(ROOT)}")

    sitemap = (ROOT / "sitemap.xml").read_text(encoding="utf-8")
    if "<loc>https://skuraganti.github.io/</loc>" not in sitemap:
        fail("sitemap.xml: home URL missing")
    if "Sitemap: https://skuraganti.github.io/sitemap.xml" not in (ROOT / "robots.txt").read_text():
        fail("robots.txt: sitemap line missing")

    if html.count('href="mailto:' + PUBLIC_EMAIL + '"') != 1:
        fail("index.html: expected exactly one mailto link to the public email")

    if failures:
        print("FAIL")
        for f in failures:
            print(" -", f)
        return 1
    print(f"OK: {len(PAGES)} pages, {len(REQUIRED_FILES)} required files, all checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
